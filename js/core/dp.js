// ==========================================
// DARK PEONY — ядро: пространство имён, конфиг, утилиты, общие uniform'ы
// ==========================================
// Все модули подключаются обычными <script> (без сборки и без ES-модулей),
// поэтому сайт открывается и с GitHub Pages, и двойным кликом по index.html.
(function (global) {
    'use strict';

    const DP = global.DP = global.DP || {};
    const params = new URLSearchParams(global.location.search);
    DP.params = params;

    // ------------------------------------------
    // КОНФИГ
    // ------------------------------------------
    DP.config = {
        clearColor: 0x000102,
        maxPixelRatio: 2,
        // Размеры точек подбирались на экранах с DPR = 2 (MacBook, iPhone c ограничением до 2).
        // gl_PointSize задаётся в физических пикселях, поэтому без поправки на обычных
        // мониторах (DPR = 1) точки выглядели бы вдвое крупнее. Поправка = pixelRatio / 2.
        pointSizeRefPixelRatio: 2,
        stageRotationSpeed: 0.03,

        // Адаптивное качество: если FPS долго ниже порога — понижаем pixelRatio ступенями.
        adaptive: {
            enabled: params.get('adaptive') !== '0',
            minFps: 40,
            minPixelRatio: 1,
            step: 0.25,
            sampleSeconds: 2.5,
            warmupSeconds: 3
        },

        morph: {
            // --- расписание (секунды от начала морфинга) ---
            // Уход и посадка перекрываются: первые частицы уже садятся в новую фигуру,
            // пока последние только срываются.
            leaveStart: 0.2,       // первая частица отрывается
            leaveSpread: 6.0,      // за сколько фронт распада проходит всю фигуру
            arriveStart: 5.2,      // самая ранняя посадка в новую фигуру
            arriveSpread: 6.0,     // за сколько новая фигура собирается целиком
            minTravel: 4.6,        // минимум времени полёта одной частицы
            maxTravel: 8.0,        // максимум
            travelJitter: 0.4,     // разброс времени прилёта — плавный по месту (соседи летят синхронно)
            turns: 1,              // оборотов вокруг оси: 1 = 360° (± разница углов старта и финиша)
            assemble: 'outside-in', // 'outside-in' — сборка тоже от краёв к центру и низу, 'inside-out' — от центра к краям

            // --- кольцо в середине пути (пространство сцены, ось Y = ось стебля) ---
            // Сечение кольца — как крыло: толстое скруглённое место ближе к оси,
            // к краям сечение сходит на нет острыми концами; дальний тонкий «хвост» даёт
            // редкие частицы далеко за основным бубликом.
            ringMode: false,       // true — частицы сводятся в общее кольцо; false — каждая остаётся на своём уровне и радиусе
            ringInner: 0.6,        // внутренний острый край сечения (радиус)
            ringOuter: 3.7,        // внешний острый край сечения (радиус, максимум 3.99)
            ringPeak: 0.3,         // где сечение толще всего: 0 — у внутреннего края, 1 — у внешнего
            ringThickness: 0.75,   // половина толщины сечения в самом толстом месте
            ringSharp: 1.3,        // заострённость концов: 1 — линза, больше — тоньше и длиннее кончики
            ringY: 0.25,           // высота средней линии кольца
            threadCell: 0,         // нити: шаг сетки сечения (меньше — больше тонких нитей; 0 — без нитей)
            twistPerTurn: 0,       // перекрутов ленты-кольца за один оборот вокруг оси (0 — без перекрута)
            twistSpeed: 0,         // скорость, с которой лента проворачивается (рад/с); 0 — выкл. (иначе частицы ходят внутрь-наружу)
            twistSquash: 0.55,     // сжатие ленты по высоте, когда она встаёт «на ребро»
            cloudMix: 0.1,         // 0 — точка цветка непрерывно переходит в «свою» точку кольца, 1 — случайная точка кольца
            lift: 0,               // случайный подъём частиц (0 — слой остаётся цельным)
            swirlHold: 0.15,       // доля пути по обе стороны от середины, которую частица целиком проводит в вихре

            // --- поле течения (аналог Turbulence Field в Particular) ---
            flowAmp: 0.3,          // сила крупной волны: слой изгибается, поднимается, опускается
            flowFreq: 0.6,         // частота крупной волны (больше — чаще волны)
            flowDetailAmp: 0.08,   // сила мелких складок
            flowDetailFreq: 1.6,   // частота мелких складок
            flowSpeed: 0.3,        // скорость «дыхания» поля
            jitter: 0,             // индивидуальное дрожание частиц
            precession: 0.08,      // покачивание всего вихря
            shiver: 0,             // дрожь частиц перед отрывом (давала «дребезжание» щупалец)

            // --- стягивание в перепонки, жгуты и волокна (частицы светятся за счёт скучивания) ---
            clumpStrength: 0,      // 0 — выкл. (давало хаос), 1 — полностью на поверхность
            clumpFreq: 1.0,        // частота структуры: больше — мельче ячейки и тоньше жгуты
            clumpFilaments: 1.0,   // 0 — перепонки (плёнки), 1 — жгуты (линии пересечения перепонок)
            clumpMaxDist: 0.4,     // насколько далеко частица может «прыгнуть» к поверхности (в ед. шума)
            clumpFraction: 0.95,   // доля стягиваемых частиц, остальные — пыль вокруг
            clumpLevels: 0.12,     // шаг волокон: частицы ложатся на параллельные слои шума (0 — выкл.)
            clumpFibers: 0,        // доля частиц в волокнах (пока выкл.: давало муть); остальные — в жгутах
            clumpRamp: 0.3,        // как рано в полёте частица «прилипает» к структуре (меньше — раньше)
            clumpSpeed: 0.35,      // скорость, с которой жгуты и перепонки меняют форму (ползут, рвутся, пересоединяются)
            fieldSpin: 0.45,       // поля вращаются вместе с вихрем: 0 — стоят на месте, 1 — со скоростью частиц
            fieldShear: 0.15,       // у оси поле крутится быстрее, чем снаружи (рад/с): наматывает структуры в спирали

            // --- вид частиц в полёте ---
            swirlColor: [0.55, 0.8, 1.0],
            swirlSize: 1.0,        // множитель размера частиц в полёте (1 — без изменений)
            swirlSizeMin: 1.0,     // размер «мелких» частиц; <1 — часть частиц мельче в полёте (пока отключено)
            swirlAlpha: 0.15,      // яркость частицы в вихре (вихрь светится за счёт скучивания)
            swirlLook: 0.3,        // 0 — в полёте частица выглядит как на цветке (чёткий рисунок), 1 — цвет/яркость вихря
            swirlBlend: 3.0,       // как поздно частица набирает яркость вихря: больше — дольше остаётся как на лепестке
            swirlTint: 0.3,        // как рано меняется цвет на цвет вихря (0 — поздно, 1 — сразу)
            leaveGlow: 0,          // подсветка перед отрывом (1 — прежняя, яркая)
            swirlVisible: 0.85,    // доля частиц, заметных в полёте (остальные — едва видимая пыль)
            dustAlpha: 0.2,

            // --- лидеры и хвосты: соседние частицы летят за лидером с задержкой ---
            trailLength: 1,        // частиц в хвосте (1 — без хвостов)
            trailLag: 0.012,       // задержка между соседями в хвосте, с (длиннее — длиннее и реже хвост)
            trailFade: 0.7,        // насколько тускнеет конец хвоста        // яркость нестянутой пыли относительно частиц в структурах

            // --- режим MESH ---
            meshRevealLag: 0.35,   // поверхность новой фигуры проявляется чуть позже посадки частиц
            meshFade: 0.9          // частицы гаснут после посадки, уступая поверхности
        }
    };

    // ------------------------------------------
    // КАЧЕСТВО
    // ------------------------------------------
    // high — эталон (1.1 млн точек; проверено на MacBook M3 Max и iPhone 15).
    // medium/low — для слабых устройств; плотность компенсируется размером и яркостью точек.
    DP.QUALITY_TIERS = {
        high:   { petalSegments: 100, petalMultiplier: 3 },
        medium: { petalSegments: 80,  petalMultiplier: 2 },
        low:    { petalSegments: 60,  petalMultiplier: 2 }
    };

    function detectQuality() {
        const forced = params.get('q');
        if (forced && DP.QUALITY_TIERS[forced]) return forced;
        const mem = navigator.deviceMemory || 8;          // нет в Safari/Firefox → считаем «достаточно»
        const cores = navigator.hardwareConcurrency || 8;
        if (mem <= 2 || cores <= 2) return 'low';
        if (mem <= 3 || cores <= 4) return 'medium';
        return 'high';
    }
    DP.quality = detectQuality();

    // ------------------------------------------
    // УТИЛИТЫ
    // ------------------------------------------
    DP.util = {
        seededRandom(seed) {
            const x = Math.sin(seed++) * 10000;
            return x - Math.floor(x);
        },
        noise(u, seed = 0) {
            return Math.sin(u * 7.3 + seed) * 0.4 + Math.sin(u * 17.1 + seed * 2.0) * 0.35 + Math.cos(u * 31.7 + seed * 0.5) * 0.25;
        },
        smoothstep(e0, e1, x) {
            const t = Math.min(1, Math.max(0, (x - e0) / (e1 - e0)));
            return t * t * (3 - 2 * t);
        },
        clamp(x, a, b) { return x < a ? a : (x > b ? b : x); },
        // Азимут вокруг оси Y; должен совпадать с dpAzimuth() в GLSL (js/core/morph.js)
        azimuth(x, z) { return (Math.abs(x) + Math.abs(z) < 1e-5) ? 0 : Math.atan2(x, z); },
        wrapPi(a) { return a - Math.PI * 2 * Math.floor((a + Math.PI) / (Math.PI * 2)); }
    };

    // ------------------------------------------
    // ОБЩИЕ UNIFORM'Ы
    // ------------------------------------------
    // Один и тот же объект {value} подставляется во все материалы — обновляем в одном месте.
    DP.shared = {
        uTime: { value: 0 },
        uViewportScale: { value: 1 },
        uTexture: { value: null } // текстура частицы, создаётся в stage.js
    };

    // Размер точек «как на эталоне»: логика стороны экрана — авторская (см. комментарий),
    // плюс поправка на плотность пикселей.
    DP.computeViewportScale = function (w, h, pixelRatio) {
        // Пока экран горизонтальный или квадратный (w >= h), берём меньшую сторону (h).
        // Как только экран становится вертикальным (w < h), фиксируем размер по высоте (h),
        // чтобы при дальнейшем сужении ширины масштаб не уменьшался (иначе «проваливается» центр).
        const effectiveDim = w >= h ? Math.min(w, h) : h;
        return effectiveDim * 0.0012 * (pixelRatio / DP.config.pointSizeRefPixelRatio);
    };

    // ------------------------------------------
    // ПРОСТЕЙШИЕ СОБЫТИЯ
    // ------------------------------------------
    DP.createEmitter = function () {
        const map = {};
        return {
            on(name, fn) { (map[name] = map[name] || []).push(fn); return () => this.off(name, fn); },
            off(name, fn) { map[name] = (map[name] || []).filter(f => f !== fn); },
            emit(name, data) { (map[name] || []).slice().forEach(fn => { try { fn(data); } catch (e) { console.error(e); } }); }
        };
    };
})(window);
